#!/usr/bin/env python3

import argparse
import csv
import math
import statistics
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

from scipy.stats import t as student_t


MODEL_ORDER = {
    "sequential": 0,
    "cmp": 1,
    "smt_hw": 2,
    "smt_sw": 3,
    "smt": 4,
    "coarse_grained": 5,
    "fine_grained": 6,
}

SUPPORTED_MODELS = set(MODEL_ORDER)


@dataclass(frozen=True)
class Sample:
    run: int
    model: str
    logical_threads: int
    rows: int
    cols: int
    steps: int
    alpha: float
    dt: float
    cell_updates: int
    elapsed_seconds: float
    cell_updates_per_second: float


@dataclass(frozen=True)
class ConfidenceInterval:
    lower: float
    upper: float


@dataclass(frozen=True)
class GroupStatistics:
    model: str
    logical_threads: int
    sample_count: int
    mean_seconds: float
    median_seconds: float
    std_seconds: float
    cv_percent: float
    minimum_seconds: float
    maximum_seconds: float
    time_ci95: ConfidenceInterval
    time_ci95_relative_half_width_percent: float
    mean_updates_per_second: float
    throughput_ci95: ConfidenceInterval
    mean_speedup_vs_sequential: float
    speedup_vs_sequential_ci95: ConfidenceInterval
    mean_model_scalability: float
    model_scalability_ci95: ConfidenceInterval
    mean_model_efficiency: float
    model_efficiency_ci95: ConfidenceInterval
    convergence_last_10_percent_change_percent: float


def parse_arguments():
    parser = argparse.ArgumentParser(
        description=(
            "Analyze raw Heat2D benchmark measurements and generate "
            "a statistical summary."
        )
    )

    parser.add_argument(
        "input_csv",
        type=Path,
        help="Raw CSV generated by heat2d_benchmark.",
    )

    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help="Summary CSV output path. Default: <input>_summary.csv",
    )

    return parser.parse_args()


def load_samples(path: Path):
    required_columns = {
        "run",
        "model",
        "logical_threads",
        "rows",
        "cols",
        "steps",
        "alpha",
        "dt",
        "cell_updates",
        "elapsed_seconds",
        "cell_updates_per_second",
    }

    samples = []

    with path.open(
        "r",
        newline="",
        encoding="utf-8",
    ) as file:

        reader = csv.DictReader(file)

        if reader.fieldnames is None:
            raise ValueError(
                "CSV does not contain a header."
            )

        missing_columns = (
            required_columns -
            set(reader.fieldnames)
        )

        if missing_columns:
            raise ValueError(
                "CSV is missing required columns: "
                + ", ".join(
                    sorted(missing_columns)
                )
            )

        for row in reader:
            sample = Sample(
                run=int(
                    row["run"]
                ),
                model=row["model"],
                logical_threads=int(
                    row["logical_threads"]
                ),
                rows=int(
                    row["rows"]
                ),
                cols=int(
                    row["cols"]
                ),
                steps=int(
                    row["steps"]
                ),
                alpha=float(
                    row["alpha"]
                ),
                dt=float(
                    row["dt"]
                ),
                cell_updates=int(
                    row["cell_updates"]
                ),
                elapsed_seconds=float(
                    row["elapsed_seconds"]
                ),
                cell_updates_per_second=float(
                    row["cell_updates_per_second"]
                ),
            )

            validate_sample(
                sample
            )

            samples.append(
                sample
            )

    if not samples:
        raise ValueError(
            "CSV does not contain benchmark samples."
        )

    return samples


def validate_sample(sample: Sample):
    if sample.run <= 0:
        raise ValueError(
            "Run identifiers must be positive."
        )

    if sample.model not in SUPPORTED_MODELS:
        raise ValueError(
            f"Unsupported execution model: {sample.model}"
        )

    if sample.logical_threads <= 0:
        raise ValueError(
            "Execution-context count must be positive."
        )

    if (
        sample.model == "sequential"
        and sample.logical_threads != 1
    ):
        raise ValueError(
            "Sequential samples must use one execution context."
        )

    if (
        sample.rows < 3 or
        sample.cols < 3
    ):
        raise ValueError(
            "Grid dimensions must be at least 3x3."
        )

    if sample.steps <= 0:
        raise ValueError(
            "Step count must be positive."
        )

    if sample.cell_updates <= 0:
        raise ValueError(
            "Cell-update count must be positive."
        )

    if (
        sample.elapsed_seconds <= 0.0
        or not math.isfinite(
            sample.elapsed_seconds
        )
    ):
        raise ValueError(
            "CSV contains an invalid execution time."
        )

    if (
        sample.cell_updates_per_second <= 0.0
        or not math.isfinite(
            sample.cell_updates_per_second
        )
    ):
        raise ValueError(
            "CSV contains invalid throughput."
        )


def validate_common_workload(samples):
    reference = samples[0]

    for sample in samples[1:]:
        if (
            sample.rows != reference.rows
            or sample.cols != reference.cols
            or sample.steps != reference.steps
            or sample.alpha != reference.alpha
            or sample.dt != reference.dt
            or sample.cell_updates
            != reference.cell_updates
        ):
            raise ValueError(
                "Benchmark samples do not share "
                "the same numerical workload."
            )


def group_samples(samples):
    groups = defaultdict(list)

    for sample in samples:
        key = (
            sample.model,
            sample.logical_threads,
        )

        groups[key].append(
            sample
        )

    for group in groups.values():
        group.sort(
            key=lambda sample:
                sample.run
        )

    return groups


def validate_groups(groups):
    sequential_key = (
        "sequential",
        1,
    )

    if sequential_key not in groups:
        raise ValueError(
            "Sequential baseline is missing."
        )

    sequential_group = groups[
        sequential_key
    ]

    sequential_runs = {
        sample.run
        for sample in sequential_group
    }

    if (
        len(sequential_runs)
        != len(sequential_group)
    ):
        raise ValueError(
            "Sequential baseline contains "
            "duplicate run identifiers."
        )

    # Si un modelo no tiene corrida de 1 hilo, se usará el baseline secuencial

    for key, group in groups.items():
        run_ids = {
            sample.run
            for sample in group
        }

        if len(run_ids) != len(group):
            raise ValueError(
                f"Benchmark group {key} contains "
                "duplicate run identifiers."
            )

        if run_ids != sequential_runs:
            raise ValueError(
                f"Benchmark group {key} does not "
                "contain the same run identifiers "
                "as the sequential baseline."
            )


def confidence_interval_95(values):
    if not values:
        raise ValueError(
            "Cannot calculate a confidence "
            "interval from empty data."
        )

    count = len(values)

    mean_value = statistics.fmean(
        values
    )

    if count == 1:
        return ConfidenceInterval(
            mean_value,
            mean_value,
        )

    standard_error = (
        statistics.stdev(values) /
        math.sqrt(count)
    )

    critical_value = student_t.ppf(
        0.975,
        df=count - 1,
    )

    margin = (
        critical_value *
        standard_error
    )

    return ConfidenceInterval(
        mean_value - margin,
        mean_value + margin,
    )


def coefficient_of_variation_percent(
    values
):
    mean_value = statistics.fmean(
        values
    )

    if (
        mean_value == 0.0 or
        len(values) <= 1
    ):
        return 0.0

    return (
        statistics.stdev(values) /
        mean_value *
        100.0
    )


def relative_ci_half_width_percent(
    mean_value,
    interval,
):
    if mean_value == 0.0:
        return 0.0

    half_width = (
        interval.upper -
        interval.lower
    ) / 2.0

    return (
        abs(half_width) /
        abs(mean_value) *
        100.0
    )


def convergence_change_percent(
    values
):
    if len(values) <= 1:
        return 0.0

    final_mean = statistics.fmean(
        values
    )

    if final_mean == 0.0:
        return 0.0

    checkpoint_count = max(
        1,
        math.floor(
            len(values) * 0.90
        ),
    )

    if checkpoint_count >= len(values):
        checkpoint_count = (
            len(values) - 1
        )

    checkpoint_mean = statistics.fmean(
        values[:checkpoint_count]
    )

    return (
        abs(
            final_mean -
            checkpoint_mean
        ) /
        abs(final_mean) *
        100.0
    )


def paired_ratios(
    reference_samples,
    candidate_samples,
):
    reference_by_run = {
        sample.run: sample
        for sample in reference_samples
    }

    candidate_by_run = {
        sample.run: sample
        for sample in candidate_samples
    }

    return [
        reference_by_run[
            run
        ].elapsed_seconds
        /
        candidate_by_run[
            run
        ].elapsed_seconds
        for run in sorted(
            reference_by_run
        )
    ]


def calculate_statistics(
    groups
):
    sequential_samples = groups[
        (
            "sequential",
            1,
        )
    ]

    results = []

    for (
        model,
        logical_threads
    ), samples in groups.items():

        times = [
            sample.elapsed_seconds
            for sample in samples
        ]

        throughputs = [
            sample.cell_updates_per_second
            for sample in samples
        ]

        mean_seconds = statistics.fmean(
            times
        )

        median_seconds = statistics.median(
            times
        )

        std_seconds = (
            statistics.stdev(times)
            if len(times) > 1
            else 0.0
        )

        cv_percent = (
            coefficient_of_variation_percent(
                times
            )
        )

        time_ci95 = (
            confidence_interval_95(
                times
            )
        )

        time_ci95_relative_half_width_percent = (
            relative_ci_half_width_percent(
                mean_seconds,
                time_ci95,
            )
        )

        mean_throughput = statistics.fmean(
            throughputs
        )

        throughput_ci95 = confidence_interval_95(
            throughputs
        )

        if model == "sequential":
            speedups_vs_sequential = [
                1.0
                for _ in samples
            ]

            model_scalabilities = [
                1.0
                for _ in samples
            ]

        else:
            speedups_vs_sequential = (
                paired_ratios(
                    sequential_samples,
                    samples,
                )
            )

            baseline_model_samples = (
                groups[(model, 1)]
                if (model, 1) in groups
                else sequential_samples
            )

            model_scalabilities = (
                paired_ratios(
                    baseline_model_samples,
                    samples,
                )
            )

        model_efficiencies = [
            scalability /
            logical_threads
            for scalability
            in model_scalabilities
        ]

        results.append(
            GroupStatistics(
                model=model,
                logical_threads=(
                    logical_threads
                ),
                sample_count=len(
                    samples
                ),
                mean_seconds=(
                    mean_seconds
                ),
                median_seconds=(
                    median_seconds
                ),
                std_seconds=(
                    std_seconds
                ),
                cv_percent=(
                    cv_percent
                ),
                minimum_seconds=min(
                    times
                ),
                maximum_seconds=max(
                    times
                ),
                time_ci95=(
                    time_ci95
                ),
                time_ci95_relative_half_width_percent=(
                    time_ci95_relative_half_width_percent
                ),
                mean_updates_per_second=(
                    mean_throughput
                ),
                throughput_ci95=(
                    throughput_ci95
                ),
                mean_speedup_vs_sequential=(
                    statistics.fmean(
                        speedups_vs_sequential
                    )
                ),
                speedup_vs_sequential_ci95=(
                    confidence_interval_95(
                        speedups_vs_sequential
                    )
                ),
                mean_model_scalability=(
                    statistics.fmean(
                        model_scalabilities
                    )
                ),
                model_scalability_ci95=(
                    confidence_interval_95(
                        model_scalabilities
                    )
                ),
                mean_model_efficiency=(
                    statistics.fmean(
                        model_efficiencies
                    )
                ),
                model_efficiency_ci95=(
                    confidence_interval_95(
                        model_efficiencies
                    )
                ),
                convergence_last_10_percent_change_percent=(
                    convergence_change_percent(
                        times
                    )
                ),
            )
        )

    return sorted(
        results,
        key=lambda result: (
            MODEL_ORDER[
                result.model
            ],
            result.logical_threads,
        ),
    )


def default_summary_path(
    input_path: Path
):
    return input_path.with_name(
        input_path.stem +
        "_summary.csv"
    )


def write_summary_csv(
    path: Path,
    results
):
    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    header = [
        "model",
        "logical_threads",
        "n",
        "mean_seconds",
        "median_seconds",
        "std_seconds",
        "cv_percent",
        "minimum_seconds",
        "maximum_seconds",
        "time_ci95_low",
        "time_ci95_high",
        "time_ci95_relative_half_width_percent",
        "mean_mupdates_per_second",
        "throughput_ci95_low_mupdates",
        "throughput_ci95_high_mupdates",
        "mean_speedup_vs_sequential",
        "speedup_vs_sequential_ci95_low",
        "speedup_vs_sequential_ci95_high",
        "mean_model_scalability",
        "model_scalability_ci95_low",
        "model_scalability_ci95_high",
        "mean_model_efficiency",
        "model_efficiency_ci95_low",
        "model_efficiency_ci95_high",
        "convergence_last_10_percent_change_percent",
    ]

    with path.open(
        "w",
        newline="",
        encoding="utf-8",
    ) as file:

        writer = csv.writer(
            file
        )

        writer.writerow(
            header
        )

        for result in results:
            writer.writerow(
                [
                    result.model,
                    result.logical_threads,
                    result.sample_count,
                    result.mean_seconds,
                    result.median_seconds,
                    result.std_seconds,
                    result.cv_percent,
                    result.minimum_seconds,
                    result.maximum_seconds,
                    result.time_ci95.lower,
                    result.time_ci95.upper,
                    result.time_ci95_relative_half_width_percent,
                    (
                        result.mean_updates_per_second /
                        1_000_000.0
                    ),
                    (
                        result.throughput_ci95.lower /
                        1_000_000.0
                    ),
                    (
                        result.throughput_ci95.upper /
                        1_000_000.0
                    ),
                    result.mean_speedup_vs_sequential,
                    result.speedup_vs_sequential_ci95.lower,
                    result.speedup_vs_sequential_ci95.upper,
                    result.mean_model_scalability,
                    result.model_scalability_ci95.lower,
                    result.model_scalability_ci95.upper,
                    result.mean_model_efficiency,
                    result.model_efficiency_ci95.lower,
                    result.model_efficiency_ci95.upper,
                    result.convergence_last_10_percent_change_percent,
                ]
            )


def efficiency_name(
    model
):
    if model in {
        "coarse_grained",
        "cmp",
        "smt",
    }:
        return "parallel"

    if model == "fine_grained":
        return "logical"

    return "reference"


def print_summary(
    samples,
    results,
    output_path,
):
    reference = samples[0]

    print()
    print(
        "=== Heat2D Benchmark Analysis ==="
    )
    print()

    print(
        f"Grid: "
        f"{reference.rows} x "
        f"{reference.cols}"
    )

    print(
        f"Steps: "
        f"{reference.steps}"
    )

    print(
        f"Cell updates/run: "
        f"{reference.cell_updates}"
    )

    print(
        f"Total raw samples: "
        f"{len(samples)}"
    )

    print(
        "Confidence interval: 95%"
    )

    print(
        "CI method: Student t"
    )

    print(
        "Speedup vs Sequential: paired by run"
    )

    print(
        "Model scalability: paired model-1 time / model-p time"
    )

    print(
        "CG efficiency: model scalability / real worker threads"
    )

    print(
        "CMP efficiency: model scalability / real worker threads"
    )

    print(
        "SMT efficiency: model scalability / hardware worker threads"
    )

    print(
        "FG efficiency: model scalability / simulated logical contexts "
        "(not hardware parallel efficiency)"
    )

    print()

    header = (
        f"{'Model':<15}"
        f"{'Thr':>5}"
        f"{'N':>5}"
        f"{'Mean(s)':>11}"
        f"{'CV%':>8}"
        f"{'CIhalf%':>10}"
        f"{'MUpd/s':>11}"
        f"{'SpdSeq':>10}"
        f"{'Scale':>10}"
        f"{'Eff':>10}"
        f"{'Conv10%':>10}"
    )

    print(
        header
    )

    print(
        "-" * len(header)
    )

    for result in results:
        mupdates = (
            result.mean_updates_per_second /
            1_000_000.0
        )

        print(
            f"{result.model:<15}"
            f"{result.logical_threads:>5}"
            f"{result.sample_count:>5}"
            f"{result.mean_seconds:>11.4f}"
            f"{result.cv_percent:>8.2f}"
            f"{result.time_ci95_relative_half_width_percent:>10.2f}"
            f"{mupdates:>11.2f}"
            f"{result.mean_speedup_vs_sequential:>10.4f}"
            f"{result.mean_model_scalability:>10.4f}"
            f"{result.mean_model_efficiency:>10.4f}"
            f"{result.convergence_last_10_percent_change_percent:>10.3f}"
        )

    print()
    print(
        "Efficiency interpretation:"
    )

    for model in (
        "fine_grained",
        "coarse_grained",
        "cmp",
        "smt",
    ):
        if any(
            result.model == model
            for result in results
        ):
            print(
                f"  {model}: "
                f"{efficiency_name(model)} efficiency"
            )

    print()

    print(
        "Convergence metric: relative change between the running mean "
        "at 90% of samples and the final mean."
    )

    print(
        "Use the convergence plot and CI relative half-width together "
        "when deciding whether more repetitions are needed."
    )

    print()

    print(
        f"Summary CSV: "
        f"{output_path}"
    )


def main():
    arguments = (
        parse_arguments()
    )

    output_path = (
        arguments.output
        if arguments.output is not None
        else default_summary_path(
            arguments.input_csv
        )
    )

    samples = load_samples(
        arguments.input_csv
    )

    validate_common_workload(
        samples
    )

    groups = group_samples(
        samples
    )

    validate_groups(
        groups
    )

    results = calculate_statistics(
        groups
    )

    write_summary_csv(
        output_path,
        results
    )

    print_summary(
        samples,
        results,
        output_path,
    )


if __name__ == "__main__":
    main()