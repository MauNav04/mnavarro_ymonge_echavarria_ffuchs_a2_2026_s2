#!/usr/bin/env python3

import argparse
import csv
import math
import statistics
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

try:
    from scipy.stats import t as student_t
except ImportError:
    student_t = None


@dataclass
class Sample:
    run: int
    model: str
    logical_threads: int
    rows: int
    cols: int
    steps: int
    alpha: float
    dt: float
    cell_updates: int
    elapsed_seconds: float
    cell_updates_per_second: float


@dataclass
class Statistics:
    model: str
    logical_threads: int
    sample_count: int

    mean_seconds: float
    median_seconds: float
    std_seconds: float

    minimum_seconds: float
    maximum_seconds: float

    ci95_lower: float
    ci95_upper: float

    mean_updates_per_second: float

    speedup: float
    efficiency: float


def parse_arguments():
    parser = argparse.ArgumentParser(
        description="Analyze raw Heat2D benchmark measurements."
    )

    parser.add_argument(
        "input_csv",
        type=Path,
        help="Raw CSV generated by heat2d_benchmark.",
    )

    return parser.parse_args()


def load_samples(path: Path):
    samples = []

    with path.open("r", newline="") as file:
        reader = csv.DictReader(file)

        required_columns = {
            "run",
            "model",
            "logical_threads",
            "rows",
            "cols",
            "steps",
            "alpha",
            "dt",
            "cell_updates",
            "elapsed_seconds",
            "cell_updates_per_second",
        }

        if reader.fieldnames is None:
            raise ValueError("CSV does not contain a header.")

        missing_columns = (
            required_columns -
            set(reader.fieldnames)
        )

        if missing_columns:
            raise ValueError(
                "CSV is missing required columns: "
                + ", ".join(sorted(missing_columns))
            )

        for row in reader:
            sample = Sample(
                run=int(row["run"]),
                model=row["model"],
                logical_threads=int(
                    row["logical_threads"]
                ),
                rows=int(row["rows"]),
                cols=int(row["cols"]),
                steps=int(row["steps"]),
                alpha=float(row["alpha"]),
                dt=float(row["dt"]),
                cell_updates=int(
                    row["cell_updates"]
                ),
                elapsed_seconds=float(
                    row["elapsed_seconds"]
                ),
                cell_updates_per_second=float(
                    row["cell_updates_per_second"]
                ),
            )

            if (
                sample.elapsed_seconds <= 0.0
                or not math.isfinite(
                    sample.elapsed_seconds
                )
            ):
                raise ValueError(
                    "CSV contains an invalid execution time."
                )

            samples.append(sample)

    if not samples:
        raise ValueError(
            "CSV does not contain benchmark samples."
        )

    return samples


def validate_common_workload(samples):
    reference = samples[0]

    for sample in samples[1:]:
        if (
            sample.rows != reference.rows
            or sample.cols != reference.cols
            or sample.steps != reference.steps
            or sample.alpha != reference.alpha
            or sample.dt != reference.dt
            or sample.cell_updates
            != reference.cell_updates
        ):
            raise ValueError(
                "Benchmark samples do not share "
                "the same numerical workload."
            )


def group_samples(samples):
    groups = defaultdict(list)

    for sample in samples:
        key = (
            sample.model,
            sample.logical_threads,
        )

        groups[key].append(sample)

    return groups


def confidence_interval_95(values):
    count = len(values)

    mean = statistics.fmean(values)

    if count == 1:
        return mean, mean

    standard_deviation = statistics.stdev(
        values
    )

    standard_error = (
        standard_deviation /
        math.sqrt(count)
    )

    if student_t is not None:
        critical_value = student_t.ppf(
            0.975,
            df=count - 1
        )
    else:
        # For large experimental samples such as n=200,
        # the normal approximation is nearly identical.
        critical_value = 1.96

    margin = (
        critical_value *
        standard_error
    )

    return (
        mean - margin,
        mean + margin,
    )


def calculate_group_statistics(
    groups
):
    sequential_key = (
        "sequential",
        1,
    )

    if sequential_key not in groups:
        raise ValueError(
            "Sequential baseline is missing."
        )

    sequential_times = [
        sample.elapsed_seconds
        for sample
        in groups[sequential_key]
    ]

    sequential_mean = statistics.fmean(
        sequential_times
    )

    results = []

    for (
        model,
        logical_threads
    ), samples in groups.items():

        times = [
            sample.elapsed_seconds
            for sample in samples
        ]

        throughputs = [
            sample.cell_updates_per_second
            for sample in samples
        ]

        mean_seconds = statistics.fmean(
            times
        )

        median_seconds = statistics.median(
            times
        )

        standard_deviation = (
            statistics.stdev(times)
            if len(times) > 1
            else 0.0
        )

        minimum_seconds = min(times)
        maximum_seconds = max(times)

        (
            ci95_lower,
            ci95_upper,
        ) = confidence_interval_95(
            times
        )

        mean_throughput = statistics.fmean(
            throughputs
        )

        speedup = (
            sequential_mean /
            mean_seconds
        )

        if model == "sequential":
            efficiency = 1.0
        else:
            efficiency = (
                speedup /
                logical_threads
            )

        results.append(
            Statistics(
                model=model,
                logical_threads=logical_threads,
                sample_count=len(samples),
                mean_seconds=mean_seconds,
                median_seconds=median_seconds,
                std_seconds=standard_deviation,
                minimum_seconds=minimum_seconds,
                maximum_seconds=maximum_seconds,
                ci95_lower=ci95_lower,
                ci95_upper=ci95_upper,
                mean_updates_per_second=mean_throughput,
                speedup=speedup,
                efficiency=efficiency,
            )
        )

    return sorted(
        results,
        key=lambda result: (
            0
            if result.model == "sequential"
            else 1,
            result.logical_threads,
        ),
    )


def print_summary(
    samples,
    statistics_results
):
    reference = samples[0]

    print()
    print(
        "=== Heat2D Benchmark Analysis ==="
    )

    print()
    print(
        f"Grid: "
        f"{reference.rows} x "
        f"{reference.cols}"
    )

    print(
        f"Steps: {reference.steps}"
    )

    print(
        f"Cell updates/run: "
        f"{reference.cell_updates}"
    )

    print(
        f"Total raw samples: "
        f"{len(samples)}"
    )

    print(
        "Confidence interval: 95%"
    )

    if student_t is None:
        print(
            "CI method: normal approximation "
            "(SciPy not installed)"
        )
    else:
        print(
            "CI method: Student t"
        )

    print()

    header = (
        f"{'Model':<15}"
        f"{'Threads':>9}"
        f"{'N':>6}"
        f"{'Mean(s)':>12}"
        f"{'Median(s)':>12}"
        f"{'Std(s)':>12}"
        f"{'CI95 low':>12}"
        f"{'CI95 high':>12}"
        f"{'Speedup':>10}"
        f"{'Efficiency':>12}"
        f"{'MUpd/s':>12}"
    )

    print(header)
    print("-" * len(header))

    for result in statistics_results:
        updates_per_second_millions = (
            result.mean_updates_per_second /
            1_000_000.0
        )

        print(
            f"{result.model:<15}"
            f"{result.logical_threads:>9}"
            f"{result.sample_count:>6}"
            f"{result.mean_seconds:>12.6f}"
            f"{result.median_seconds:>12.6f}"
            f"{result.std_seconds:>12.6f}"
            f"{result.ci95_lower:>12.6f}"
            f"{result.ci95_upper:>12.6f}"
            f"{result.speedup:>10.4f}"
            f"{result.efficiency:>12.4f}"
            f"{updates_per_second_millions:>12.3f}"
        )


def main():
    arguments = parse_arguments()

    samples = load_samples(
        arguments.input_csv
    )

    validate_common_workload(
        samples
    )

    groups = group_samples(
        samples
    )

    statistics_results = (
        calculate_group_statistics(
            groups
        )
    )

    print_summary(
        samples,
        statistics_results
    )


if __name__ == "__main__":
    main()