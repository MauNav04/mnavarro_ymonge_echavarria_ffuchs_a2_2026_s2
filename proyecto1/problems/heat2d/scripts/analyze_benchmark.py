#!/usr/bin/env python3

import argparse
import csv
import math
import statistics

from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

from scipy.stats import t as student_t


@dataclass(frozen=True)
class Sample:
    run: int
    model: str
    logical_threads: int

    rows: int
    cols: int
    steps: int

    alpha: float
    dt: float

    cell_updates: int

    elapsed_seconds: float
    cell_updates_per_second: float


@dataclass(frozen=True)
class ConfidenceInterval:
    lower: float
    upper: float


@dataclass(frozen=True)
class GroupStatistics:
    model: str
    logical_threads: int
    sample_count: int

    mean_seconds: float
    median_seconds: float
    std_seconds: float
    cv_percent: float

    minimum_seconds: float
    maximum_seconds: float

    time_ci95: ConfidenceInterval

    mean_updates_per_second: float
    throughput_ci95: ConfidenceInterval

    mean_speedup: float
    speedup_ci95: ConfidenceInterval

    mean_logical_efficiency: float
    efficiency_ci95: ConfidenceInterval


def parse_arguments():
    parser = argparse.ArgumentParser(
        description=(
            "Analyze raw Heat2D benchmark measurements "
            "and generate a statistical summary."
        )
    )

    parser.add_argument(
        "input_csv",
        type=Path,
        help=(
            "Raw CSV generated by heat2d_benchmark."
        ),
    )

    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help=(
            "Summary CSV output path. "
            "Default: <input>_summary.csv"
        ),
    )

    return parser.parse_args()


def load_samples(path: Path):
    samples = []

    with path.open(
        "r",
        newline="",
        encoding="utf-8",
    ) as file:

        reader = csv.DictReader(file)

        required_columns = {
            "run",
            "model",
            "logical_threads",
            "rows",
            "cols",
            "steps",
            "alpha",
            "dt",
            "cell_updates",
            "elapsed_seconds",
            "cell_updates_per_second",
        }

        if reader.fieldnames is None:
            raise ValueError(
                "CSV does not contain a header."
            )

        missing_columns = (
            required_columns -
            set(reader.fieldnames)
        )

        if missing_columns:
            raise ValueError(
                "CSV is missing required columns: "
                + ", ".join(
                    sorted(missing_columns)
                )
            )

        for row in reader:
            sample = Sample(
                run=int(
                    row["run"]
                ),
                model=row["model"],
                logical_threads=int(
                    row["logical_threads"]
                ),
                rows=int(
                    row["rows"]
                ),
                cols=int(
                    row["cols"]
                ),
                steps=int(
                    row["steps"]
                ),
                alpha=float(
                    row["alpha"]
                ),
                dt=float(
                    row["dt"]
                ),
                cell_updates=int(
                    row["cell_updates"]
                ),
                elapsed_seconds=float(
                    row["elapsed_seconds"]
                ),
                cell_updates_per_second=float(
                    row[
                        "cell_updates_per_second"
                    ]
                ),
            )

            validate_sample(
                sample
            )

            samples.append(
                sample
            )

    if not samples:
        raise ValueError(
            "CSV does not contain benchmark samples."
        )

    return samples


def validate_sample(sample: Sample):
    if sample.run <= 0:
        raise ValueError(
            "Run identifiers must be positive."
        )

    if sample.logical_threads <= 0:
        raise ValueError(
            "Logical thread count must be positive."
        )

    if sample.rows < 3 or sample.cols < 3:
        raise ValueError(
            "Grid dimensions must be at least 3x3."
        )

    if sample.steps <= 0:
        raise ValueError(
            "Step count must be positive."
        )

    if sample.cell_updates <= 0:
        raise ValueError(
            "Cell-update count must be positive."
        )

    if (
        sample.elapsed_seconds <= 0.0
        or not math.isfinite(
            sample.elapsed_seconds
        )
    ):
        raise ValueError(
            "CSV contains an invalid execution time."
        )

    if (
        sample.cell_updates_per_second <= 0.0
        or not math.isfinite(
            sample.cell_updates_per_second
        )
    ):
        raise ValueError(
            "CSV contains invalid throughput."
        )


def validate_common_workload(samples):
    reference = samples[0]

    for sample in samples[1:]:
        if (
            sample.rows
            != reference.rows
            or sample.cols
            != reference.cols
            or sample.steps
            != reference.steps
            or sample.alpha
            != reference.alpha
            or sample.dt
            != reference.dt
            or sample.cell_updates
            != reference.cell_updates
        ):
            raise ValueError(
                "Benchmark samples do not share "
                "the same numerical workload."
            )


def group_samples(samples):
    groups = defaultdict(list)

    for sample in samples:
        key = (
            sample.model,
            sample.logical_threads,
        )

        groups[key].append(
            sample
        )

    for group in groups.values():
        group.sort(
            key=lambda sample:
                sample.run
        )

    return groups


def validate_groups(groups):
    sequential_key = (
        "sequential",
        1,
    )

    if sequential_key not in groups:
        raise ValueError(
            "Sequential baseline is missing."
        )

    sequential_group = groups[
        sequential_key
    ]

    sequential_runs = {
        sample.run
        for sample in sequential_group
    }

    if (
        len(sequential_runs)
        != len(sequential_group)
    ):
        raise ValueError(
            "Sequential baseline contains "
            "duplicate run identifiers."
        )

    for key, group in groups.items():
        run_ids = {
            sample.run
            for sample in group
        }

        if len(run_ids) != len(group):
            raise ValueError(
                f"Benchmark group {key} contains "
                "duplicate run identifiers."
            )

        if run_ids != sequential_runs:
            raise ValueError(
                f"Benchmark group {key} does not "
                "contain the same run identifiers "
                "as the sequential baseline."
            )


def confidence_interval_95(values):
    if not values:
        raise ValueError(
            "Cannot calculate a confidence "
            "interval from an empty sample."
        )

    count = len(values)

    mean_value = statistics.fmean(
        values
    )

    if count == 1:
        return ConfidenceInterval(
            mean_value,
            mean_value,
        )

    standard_deviation = statistics.stdev(
        values
    )

    standard_error = (
        standard_deviation /
        math.sqrt(count)
    )

    critical_value = student_t.ppf(
        0.975,
        df=count - 1,
    )

    margin = (
        critical_value *
        standard_error
    )

    return ConfidenceInterval(
        mean_value - margin,
        mean_value + margin,
    )


def calculate_coefficient_of_variation(
    values
):
    mean_value = statistics.fmean(
        values
    )

    if mean_value == 0.0:
        return 0.0

    if len(values) <= 1:
        return 0.0

    standard_deviation = (
        statistics.stdev(values)
    )

    return (
        standard_deviation /
        mean_value
    ) * 100.0


def create_run_lookup(samples):
    return {
        sample.run: sample
        for sample in samples
    }


def calculate_paired_speedups(
    sequential_samples,
    candidate_samples,
):
    sequential_by_run = (
        create_run_lookup(
            sequential_samples
        )
    )

    candidate_by_run = (
        create_run_lookup(
            candidate_samples
        )
    )

    speedups = []

    for run in sorted(
        sequential_by_run
    ):
        sequential_time = (
            sequential_by_run[
                run
            ].elapsed_seconds
        )

        candidate_time = (
            candidate_by_run[
                run
            ].elapsed_seconds
        )

        speedups.append(
            sequential_time /
            candidate_time
        )

    return speedups


def calculate_statistics(
    groups
):
    sequential_key = (
        "sequential",
        1,
    )

    sequential_samples = groups[
        sequential_key
    ]

    results = []

    for (
        model,
        logical_threads
    ), samples in groups.items():

        times = [
            sample.elapsed_seconds
            for sample in samples
        ]

        throughputs = [
            sample.cell_updates_per_second
            for sample in samples
        ]

        mean_seconds = (
            statistics.fmean(
                times
            )
        )

        median_seconds = (
            statistics.median(
                times
            )
        )

        std_seconds = (
            statistics.stdev(times)
            if len(times) > 1
            else 0.0
        )

        cv_percent = (
            calculate_coefficient_of_variation(
                times
            )
        )

        time_ci95 = (
            confidence_interval_95(
                times
            )
        )

        mean_throughput = (
            statistics.fmean(
                throughputs
            )
        )

        throughput_ci95 = (
            confidence_interval_95(
                throughputs
            )
        )

        if model == "sequential":
            speedups = [
                1.0
                for _ in samples
            ]

            efficiencies = [
                1.0
                for _ in samples
            ]

        else:
            speedups = (
                calculate_paired_speedups(
                    sequential_samples,
                    samples,
                )
            )

            efficiencies = [
                speedup /
                logical_threads
                for speedup
                in speedups
            ]

        mean_speedup = (
            statistics.fmean(
                speedups
            )
        )

        speedup_ci95 = (
            confidence_interval_95(
                speedups
            )
        )

        mean_efficiency = (
            statistics.fmean(
                efficiencies
            )
        )

        efficiency_ci95 = (
            confidence_interval_95(
                efficiencies
            )
        )

        results.append(
            GroupStatistics(
                model=model,
                logical_threads=(
                    logical_threads
                ),
                sample_count=len(
                    samples
                ),
                mean_seconds=(
                    mean_seconds
                ),
                median_seconds=(
                    median_seconds
                ),
                std_seconds=(
                    std_seconds
                ),
                cv_percent=(
                    cv_percent
                ),
                minimum_seconds=min(
                    times
                ),
                maximum_seconds=max(
                    times
                ),
                time_ci95=(
                    time_ci95
                ),
                mean_updates_per_second=(
                    mean_throughput
                ),
                throughput_ci95=(
                    throughput_ci95
                ),
                mean_speedup=(
                    mean_speedup
                ),
                speedup_ci95=(
                    speedup_ci95
                ),
                mean_logical_efficiency=(
                    mean_efficiency
                ),
                efficiency_ci95=(
                    efficiency_ci95
                ),
            )
        )

    return sorted(
        results,
        key=lambda result: (
            0
            if result.model
            == "sequential"
            else 1,
            result.logical_threads,
        ),
    )


def default_summary_path(
    input_path: Path
):
    return input_path.with_name(
        input_path.stem
        + "_summary.csv"
    )


def write_summary_csv(
    path: Path,
    results
):
    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with path.open(
        "w",
        newline="",
        encoding="utf-8",
    ) as file:

        writer = csv.writer(
            file
        )

        writer.writerow(
            [
                "model",
                "logical_threads",
                "n",
                "mean_seconds",
                "median_seconds",
                "std_seconds",
                "cv_percent",
                "minimum_seconds",
                "maximum_seconds",
                "time_ci95_low",
                "time_ci95_high",
                "mean_mupdates_per_second",
                "throughput_ci95_low_mupdates",
                "throughput_ci95_high_mupdates",
                "mean_speedup",
                "speedup_ci95_low",
                "speedup_ci95_high",
                "mean_logical_efficiency",
                "efficiency_ci95_low",
                "efficiency_ci95_high",
            ]
        )

        for result in results:
            writer.writerow(
                [
                    result.model,
                    result.logical_threads,
                    result.sample_count,
                    result.mean_seconds,
                    result.median_seconds,
                    result.std_seconds,
                    result.cv_percent,
                    result.minimum_seconds,
                    result.maximum_seconds,
                    result.time_ci95.lower,
                    result.time_ci95.upper,
                    (
                        result.mean_updates_per_second
                        / 1_000_000.0
                    ),
                    (
                        result.throughput_ci95.lower
                        / 1_000_000.0
                    ),
                    (
                        result.throughput_ci95.upper
                        / 1_000_000.0
                    ),
                    result.mean_speedup,
                    result.speedup_ci95.lower,
                    result.speedup_ci95.upper,
                    result.mean_logical_efficiency,
                    result.efficiency_ci95.lower,
                    result.efficiency_ci95.upper,
                ]
            )


def print_summary(
    samples,
    results,
    output_path,
):
    reference = samples[0]

    print()
    print(
        "=== Heat2D Benchmark Analysis ==="
    )

    print()

    print(
        f"Grid: "
        f"{reference.rows} x "
        f"{reference.cols}"
    )

    print(
        f"Steps: "
        f"{reference.steps}"
    )

    print(
        f"Cell updates/run: "
        f"{reference.cell_updates}"
    )

    print(
        f"Total raw samples: "
        f"{len(samples)}"
    )

    print(
        "Confidence interval: 95%"
    )

    print(
        "CI method: Student t"
    )

    print(
        "Speedup method: paired by run"
    )

    print()

    header = (
        f"{'Model':<15}"
        f"{'Thr':>5}"
        f"{'N':>5}"
        f"{'Mean(s)':>11}"
        f"{'Std(s)':>10}"
        f"{'CV%':>8}"
        f"{'Time CI95':>23}"
        f"{'MUpd/s':>11}"
        f"{'Speedup':>10}"
        f"{'Speedup CI95':>23}"
        f"{'LogicalEff':>12}"
    )

    print(
        header
    )

    print(
        "-" * len(header)
    )

    for result in results:
        time_interval = (
            f"["
            f"{result.time_ci95.lower:.4f}, "
            f"{result.time_ci95.upper:.4f}"
            f"]"
        )

        speedup_interval = (
            f"["
            f"{result.speedup_ci95.lower:.4f}, "
            f"{result.speedup_ci95.upper:.4f}"
            f"]"
        )

        mupdates = (
            result.mean_updates_per_second /
            1_000_000.0
        )

        print(
            f"{result.model:<15}"
            f"{result.logical_threads:>5}"
            f"{result.sample_count:>5}"
            f"{result.mean_seconds:>11.4f}"
            f"{result.std_seconds:>10.4f}"
            f"{result.cv_percent:>8.2f}"
            f"{time_interval:>23}"
            f"{mupdates:>11.2f}"
            f"{result.mean_speedup:>10.4f}"
            f"{speedup_interval:>23}"
            f"{result.mean_logical_efficiency:>12.4f}"
        )

    print()

    print(
        f"Summary CSV: "
        f"{output_path}"
    )


def main():
    arguments = (
        parse_arguments()
    )

    output_path = (
        arguments.output
        if arguments.output
        is not None
        else default_summary_path(
            arguments.input_csv
        )
    )

    samples = load_samples(
        arguments.input_csv
    )

    validate_common_workload(
        samples
    )

    groups = group_samples(
        samples
    )

    validate_groups(
        groups
    )

    results = calculate_statistics(
        groups
    )

    write_summary_csv(
        output_path,
        results
    )

    print_summary(
        samples,
        results,
        output_path,
    )


if __name__ == "__main__":
    main()