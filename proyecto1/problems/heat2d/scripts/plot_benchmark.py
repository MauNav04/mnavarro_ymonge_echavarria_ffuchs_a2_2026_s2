#!/usr/bin/env python3

import argparse
import csv

from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

import matplotlib.pyplot as plt


MODEL_ORDER = {
    "sequential": 0,
    "fine_grained": 1,
    "coarse_grained": 2,
}


@dataclass(frozen=True)
class SummaryRow:
    model: str
    logical_threads: int
    sample_count: int

    mean_seconds: float
    time_ci95_low: float
    time_ci95_high: float

    mean_mupdates_per_second: float
    throughput_ci95_low: float
    throughput_ci95_high: float

    mean_speedup_vs_sequential: float
    speedup_vs_sequential_ci95_low: float
    speedup_vs_sequential_ci95_high: float

    mean_model_scalability: float
    model_scalability_ci95_low: float
    model_scalability_ci95_high: float

    mean_model_efficiency: float
    model_efficiency_ci95_low: float
    model_efficiency_ci95_high: float


@dataclass(frozen=True)
class RawSample:
    run: int
    model: str
    logical_threads: int
    elapsed_seconds: float


def parse_arguments():
    parser = argparse.ArgumentParser(
        description=(
            "Generate plots from Heat2D benchmark summary "
            "and raw CSV files."
        )
    )

    parser.add_argument(
        "summary_csv",
        type=Path,
        help="Summary CSV generated by analyze_benchmark.py.",
    )

    parser.add_argument(
        "--raw",
        type=Path,
        default=None,
        help=(
            "Raw benchmark CSV. Required for the distribution "
            "boxplot and convergence plot."
        ),
    )

    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path(
            "proyecto1/problems/heat2d/"
            "benchmark_results/plots"
        ),
        help="Directory where plot images will be written.",
    )

    return parser.parse_args()


def load_summary(path: Path):
    rows = []

    with path.open(
        "r",
        newline="",
        encoding="utf-8",
    ) as file:

        reader = csv.DictReader(file)

        required_columns = {
            "model",
            "logical_threads",
            "n",
            "mean_seconds",
            "time_ci95_low",
            "time_ci95_high",
            "mean_mupdates_per_second",
            "throughput_ci95_low_mupdates",
            "throughput_ci95_high_mupdates",
            "mean_speedup_vs_sequential",
            "speedup_vs_sequential_ci95_low",
            "speedup_vs_sequential_ci95_high",
            "mean_model_scalability",
            "model_scalability_ci95_low",
            "model_scalability_ci95_high",
            "mean_model_efficiency",
            "model_efficiency_ci95_low",
            "model_efficiency_ci95_high",
        }

        if reader.fieldnames is None:
            raise ValueError(
                "Summary CSV does not contain a header."
            )

        missing_columns = (
            required_columns -
            set(reader.fieldnames)
        )

        if missing_columns:
            raise ValueError(
                "Summary CSV is missing required columns: "
                + ", ".join(
                    sorted(missing_columns)
                )
            )

        for row in reader:
            rows.append(
                SummaryRow(
                    model=row["model"],
                    logical_threads=int(
                        row["logical_threads"]
                    ),
                    sample_count=int(
                        row["n"]
                    ),
                    mean_seconds=float(
                        row["mean_seconds"]
                    ),
                    time_ci95_low=float(
                        row["time_ci95_low"]
                    ),
                    time_ci95_high=float(
                        row["time_ci95_high"]
                    ),
                    mean_mupdates_per_second=float(
                        row["mean_mupdates_per_second"]
                    ),
                    throughput_ci95_low=float(
                        row[
                            "throughput_ci95_low_mupdates"
                        ]
                    ),
                    throughput_ci95_high=float(
                        row[
                            "throughput_ci95_high_mupdates"
                        ]
                    ),
                    mean_speedup_vs_sequential=float(
                        row[
                            "mean_speedup_vs_sequential"
                        ]
                    ),
                    speedup_vs_sequential_ci95_low=float(
                        row[
                            "speedup_vs_sequential_ci95_low"
                        ]
                    ),
                    speedup_vs_sequential_ci95_high=float(
                        row[
                            "speedup_vs_sequential_ci95_high"
                        ]
                    ),
                    mean_model_scalability=float(
                        row[
                            "mean_model_scalability"
                        ]
                    ),
                    model_scalability_ci95_low=float(
                        row[
                            "model_scalability_ci95_low"
                        ]
                    ),
                    model_scalability_ci95_high=float(
                        row[
                            "model_scalability_ci95_high"
                        ]
                    ),
                    mean_model_efficiency=float(
                        row[
                            "mean_model_efficiency"
                        ]
                    ),
                    model_efficiency_ci95_low=float(
                        row[
                            "model_efficiency_ci95_low"
                        ]
                    ),
                    model_efficiency_ci95_high=float(
                        row[
                            "model_efficiency_ci95_high"
                        ]
                    ),
                )
            )

    if not rows:
        raise ValueError(
            "Summary CSV does not contain data."
        )

    return sorted(
        rows,
        key=lambda row: (
            MODEL_ORDER.get(
                row.model,
                99,
            ),
            row.logical_threads,
        ),
    )


def load_raw_samples(path: Path):
    samples = []

    with path.open(
        "r",
        newline="",
        encoding="utf-8",
    ) as file:

        reader = csv.DictReader(file)

        required_columns = {
            "run",
            "model",
            "logical_threads",
            "elapsed_seconds",
        }

        if reader.fieldnames is None:
            raise ValueError(
                "Raw CSV does not contain a header."
            )

        missing_columns = (
            required_columns -
            set(reader.fieldnames)
        )

        if missing_columns:
            raise ValueError(
                "Raw CSV is missing required columns: "
                + ", ".join(
                    sorted(missing_columns)
                )
            )

        for row in reader:
            samples.append(
                RawSample(
                    run=int(
                        row["run"]
                    ),
                    model=row["model"],
                    logical_threads=int(
                        row["logical_threads"]
                    ),
                    elapsed_seconds=float(
                        row["elapsed_seconds"]
                    ),
                )
            )

    if not samples:
        raise ValueError(
            "Raw CSV does not contain data."
        )

    return samples


def case_label(
    model,
    logical_threads,
):
    if model == "sequential":
        return "Sequential"

    if model == "fine_grained":
        return (
            f"FG-{logical_threads}"
        )

    if model == "coarse_grained":
        return (
            f"CG-{logical_threads}"
        )

    return (
        f"{model}-{logical_threads}"
    )


def create_labels(rows):
    return [
        case_label(
            row.model,
            row.logical_threads,
        )
        for row in rows
    ]


def create_asymmetric_errors(
    means,
    lower_bounds,
    upper_bounds,
):
    lower_errors = [
        max(
            0.0,
            mean - lower,
        )
        for mean, lower
        in zip(
            means,
            lower_bounds,
        )
    ]

    upper_errors = [
        max(
            0.0,
            upper - mean,
        )
        for mean, upper
        in zip(
            means,
            upper_bounds,
        )
    ]

    return [
        lower_errors,
        upper_errors,
    ]


def finish_bar_plot(
    figure,
    axis,
):
    axis.tick_params(
        axis="x",
        labelrotation=45,
    )

    figure.tight_layout()


def save_execution_time_plot(
    rows,
    output_directory,
):
    labels = create_labels(
        rows
    )

    means = [
        row.mean_seconds
        for row in rows
    ]

    lower = [
        row.time_ci95_low
        for row in rows
    ]

    upper = [
        row.time_ci95_high
        for row in rows
    ]

    errors = create_asymmetric_errors(
        means,
        lower,
        upper,
    )

    figure, axis = plt.subplots(
        figsize=(12, 7)
    )

    axis.bar(
        labels,
        means,
        yerr=errors,
        capsize=4,
    )

    axis.set_title(
        "Heat2D execution time"
    )

    axis.set_xlabel(
        "Execution configuration"
    )

    axis.set_ylabel(
        "Mean execution time (s)"
    )

    axis.grid(
        axis="y",
        alpha=0.3,
    )

    finish_bar_plot(
        figure,
        axis,
    )

    figure.savefig(
        output_directory /
        "execution_time.png",
        dpi=200,
    )

    plt.close(
        figure
    )


