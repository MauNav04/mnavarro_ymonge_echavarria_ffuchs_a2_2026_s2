def group_raw_samples(samples):
    groups = defaultdict(list)

    for sample in samples:
        key = (
            sample.model,
            sample.logical_threads,
        )

        groups[key].append(
            sample
        )

    for group in groups.values():
        group.sort(
            key=lambda sample:
                sample.run
        )

    return groups


def sorted_raw_keys(groups):
    return sorted(
        groups,
        key=lambda key: (
            MODEL_ORDER.get(
                key[0],
                99,
            ),
            key[1],
        ),
    )


def save_distribution_boxplot(
    raw_samples,
    output_directory,
):
    groups = group_raw_samples(
        raw_samples
    )

    keys = sorted_raw_keys(
        groups
    )

    labels = [
        case_label(
            model,
            logical_threads,
        )
        for model, logical_threads
        in keys
    ]

    values = [
        [
            sample.elapsed_seconds
            for sample in groups[key]
        ]
        for key in keys
    ]

    figure, axis = plt.subplots(
        figsize=(13, 7)
    )

    axis.boxplot(
        values,
        tick_labels=labels,
        showmeans=True,
    )

    axis.set_title(
        "Heat2D execution-time distribution"
    )

    axis.set_xlabel(
        "Execution configuration"
    )

    axis.set_ylabel(
        "Execution time (s)"
    )

    axis.grid(
        axis="y",
        alpha=0.3,
    )

    axis.tick_params(
        axis="x",
        labelrotation=45,
    )

    figure.tight_layout()

    figure.savefig(
        output_directory /
        "time_distribution_boxplot.png",
        dpi=200,
    )

    plt.close(
        figure
    )


def running_means(values):
    means = []

    total = 0.0

    for index, value in enumerate(
        values,
        start=1,
    ):
        total += value

        means.append(
            total /
            index
        )

    return means


def save_convergence_plot(
    raw_samples,
    output_directory,
):
    groups = group_raw_samples(
        raw_samples
    )

    keys = sorted_raw_keys(
        groups
    )

    figure, axis = plt.subplots(
        figsize=(13, 8)
    )

    for key in keys:
        samples = groups[key]

        runs = [
            sample.run
            for sample in samples
        ]

        times = [
            sample.elapsed_seconds
            for sample in samples
        ]

        axis.plot(
            runs,
            running_means(
                times
            ),
            label=case_label(
                key[0],
                key[1],
            ),
        )

    axis.set_title(
        "Heat2D execution-time convergence"
    )

    axis.set_xlabel(
        "Measured run"
    )

    axis.set_ylabel(
        "Running mean execution time (s)"
    )

    axis.grid(
        alpha=0.3,
    )

    axis.legend(
        bbox_to_anchor=(
            1.02,
            1.0,
        ),
        loc="upper left",
    )

    figure.tight_layout()

    figure.savefig(
        output_directory /
        "convergence.png",
        dpi=200,
    )

    plt.close(
        figure
    )


def main():
    arguments = parse_arguments()

    rows = load_summary(
        arguments.summary_csv
    )

    arguments.output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    save_execution_time_plot(
        rows,
        arguments.output_dir,
    )

    save_throughput_plot(
        rows,
        arguments.output_dir,
    )

    save_speedup_plot(
        rows,
        arguments.output_dir,
    )

    save_model_scalability_plot(
        rows,
        arguments.output_dir,
    )

    save_fine_grained_efficiency_plot(
        rows,
        arguments.output_dir,
    )

    save_coarse_grained_efficiency_plot(
        rows,
        arguments.output_dir,
    )

    generated_files = [
        "execution_time.png",
        "throughput.png",
        "speedup_vs_sequential.png",
        "model_scalability.png",
        "fine_grained_logical_efficiency.png",
        "coarse_grained_parallel_efficiency.png",
    ]

    if arguments.raw is not None:
        raw_samples = load_raw_samples(
            arguments.raw
        )

        save_distribution_boxplot(
            raw_samples,
            arguments.output_dir,
        )

        save_convergence_plot(
            raw_samples,
            arguments.output_dir,
        )

        generated_files.extend(
            [
                "time_distribution_boxplot.png",
                "convergence.png",
            ]
        )

    else:
        print()
        print(
            "WARNING: --raw was not provided. "
            "Distribution and convergence plots were skipped."
        )

    print()
    print(
        "Heat2D benchmark plots generated:"
    )

    for file_name in generated_files:
        print(
            f"  {file_name}"
        )

    print()

    print(
        f"Output directory: "
        f"{arguments.output_dir}"
    )


if __name__ == "__main__":
    main()