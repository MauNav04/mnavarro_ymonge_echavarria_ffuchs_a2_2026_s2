def main():
    arguments = parse_arguments()

    rows = load_summary(
        arguments.summary_csv
    )

    arguments.output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    save_execution_time_plot(
        rows,
        arguments.output_dir,
    )

    save_throughput_plot(
        rows,
        arguments.output_dir,
    )

