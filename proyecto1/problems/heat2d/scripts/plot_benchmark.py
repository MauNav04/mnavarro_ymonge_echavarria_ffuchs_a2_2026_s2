def save_model_scalability_plot(
    rows,
    output_directory,
):
    figure, axis = plt.subplots(
        figsize=(10, 6)
    )

    found_model = False

    for model, display_name in (
        (
            "fine_grained",
            "Fine-Grained",
        ),
        (
            "coarse_grained",
            "Coarse-Grained",
        ),
    ):
        model_rows = [
            row
            for row in rows
            if row.model == model
        ]

        if not model_rows:
            continue

        found_model = True

        x_values = [
            row.logical_threads
            for row in model_rows
        ]

        y_values = [
            row.mean_model_scalability
            for row in model_rows
        ]

        axis.plot(
            x_values,
            y_values,
            marker="o",
            label=display_name,
        )

    if not found_model:
        plt.close(
            figure
        )
        return

    axis.axhline(
        y=1.0,
        linestyle="--",
        linewidth=1.0,
    )

    axis.set_xscale(
        "log",
        base=2,
    )

    axis.set_title(
        "Heat2D model scalability"
    )

    axis.set_xlabel(
        "Execution contexts / worker threads"
    )

    axis.set_ylabel(
        "Model-1 time / model-p time"
    )

    axis.grid(
        alpha=0.3,
    )

    axis.legend()

    figure.tight_layout()

    figure.savefig(
        output_directory /
        "model_scalability.png",
        dpi=200,
    )

    plt.close(
        figure
    )


