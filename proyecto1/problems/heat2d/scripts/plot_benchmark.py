#!/usr/bin/env python3

import argparse
import csv

from dataclasses import dataclass
from pathlib import Path

import matplotlib.pyplot as plt


@dataclass(frozen=True)
class SummaryRow:
    model: str
    logical_threads: int
    sample_count: int

    mean_seconds: float
    time_ci95_low: float
    time_ci95_high: float

    mean_mupdates_per_second: float
    throughput_ci95_low: float
    throughput_ci95_high: float

    mean_speedup: float
    speedup_ci95_low: float
    speedup_ci95_high: float

    mean_logical_efficiency: float
    efficiency_ci95_low: float
    efficiency_ci95_high: float


def parse_arguments():
    parser = argparse.ArgumentParser(
        description=(
            "Generate plots from a Heat2D benchmark summary CSV."
        )
    )

    parser.add_argument(
        "summary_csv",
        type=Path,
        help="Summary CSV generated by analyze_benchmark.py.",
    )

    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path(
            "proyecto1/problems/heat2d/benchmark_results/plots"
        ),
        help="Directory where plot images will be written.",
    )

    return parser.parse_args()


def load_summary(path: Path):
    rows = []

    with path.open(
        "r",
        newline="",
        encoding="utf-8",
    ) as file:

        reader = csv.DictReader(file)

        required_columns = {
            "model",
            "logical_threads",
            "n",
            "mean_seconds",
            "time_ci95_low",
            "time_ci95_high",
            "mean_mupdates_per_second",
            "throughput_ci95_low_mupdates",
            "throughput_ci95_high_mupdates",
            "mean_speedup",
            "speedup_ci95_low",
            "speedup_ci95_high",
            "mean_logical_efficiency",
            "efficiency_ci95_low",
            "efficiency_ci95_high",
        }

        if reader.fieldnames is None:
            raise ValueError(
                "Summary CSV does not contain a header."
            )

        missing_columns = (
            required_columns -
            set(reader.fieldnames)
        )

        if missing_columns:
            raise ValueError(
                "Summary CSV is missing required columns: "
                + ", ".join(
                    sorted(missing_columns)
                )
            )

        for row in reader:
            rows.append(
                SummaryRow(
                    model=row["model"],
                    logical_threads=int(
                        row["logical_threads"]
                    ),
                    sample_count=int(
                        row["n"]
                    ),
                    mean_seconds=float(
                        row["mean_seconds"]
                    ),
                    time_ci95_low=float(
                        row["time_ci95_low"]
                    ),
                    time_ci95_high=float(
                        row["time_ci95_high"]
                    ),
                    mean_mupdates_per_second=float(
                        row["mean_mupdates_per_second"]
                    ),
                    throughput_ci95_low=float(
                        row[
                            "throughput_ci95_low_mupdates"
                        ]
                    ),
                    throughput_ci95_high=float(
                        row[
                            "throughput_ci95_high_mupdates"
                        ]
                    ),
                    mean_speedup=float(
                        row["mean_speedup"]
                    ),
                    speedup_ci95_low=float(
                        row["speedup_ci95_low"]
                    ),
                    speedup_ci95_high=float(
                        row["speedup_ci95_high"]
                    ),
                    mean_logical_efficiency=float(
                        row[
                            "mean_logical_efficiency"
                        ]
                    ),
                    efficiency_ci95_low=float(
                        row[
                            "efficiency_ci95_low"
                        ]
                    ),
                    efficiency_ci95_high=float(
                        row[
                            "efficiency_ci95_high"
                        ]
                    ),
                )
            )

    if not rows:
        raise ValueError(
            "Summary CSV does not contain data."
        )

    return rows


def create_labels(rows):
    labels = []

    for row in rows:
        if row.model == "sequential":
            labels.append(
                "Sequential"
            )
        else:
            labels.append(
                f"FG-{row.logical_threads}"
            )

    return labels


def create_asymmetric_errors(
    means,
    lower_bounds,
    upper_bounds,
):
    lower_errors = [
        mean - lower
        for mean, lower
        in zip(
            means,
            lower_bounds,
        )
    ]

    upper_errors = [
        upper - mean
        for mean, upper
        in zip(
            means,
            upper_bounds,
        )
    ]

    return [
        lower_errors,
        upper_errors,
    ]


def save_execution_time_plot(
    rows,
    output_directory,
):
    labels = create_labels(
        rows
    )

    means = [
        row.mean_seconds
        for row in rows
    ]

    lower = [
        row.time_ci95_low
        for row in rows
    ]

    upper = [
        row.time_ci95_high
        for row in rows
    ]

    errors = create_asymmetric_errors(
        means,
        lower,
        upper,
    )

    figure, axis = plt.subplots(
        figsize=(10, 6)
    )

    axis.bar(
        labels,
        means,
        yerr=errors,
        capsize=5,
    )

    axis.set_title(
        "Heat2D execution time"
    )

    axis.set_xlabel(
        "Execution model"
    )

    axis.set_ylabel(
        "Mean execution time (s)"
    )

    axis.grid(
        axis="y",
        alpha=0.3,
    )

    figure.tight_layout()

    figure.savefig(
        output_directory /
        "execution_time.png",
        dpi=200,
    )

    plt.close(
        figure
    )


